package main

// Translations preset generator (D-Pinax + D-i18n, M45). Produces internal/pinax/presets/translations.yaml
// — (entityType, key, names{locale->text}) records the pinax `translations` handler resolves to the
// i18n store. Locales: ukr/eng/spa/por (drawn from CLDR uk / en / es-419 / pt = Brazilian). CLDR supplies
// real names for countries, writing systems (scripts) and CLDR-known languages; colors, religions and
// ranks are hand-curated (no multilingual upstream). Ethnicities have no translation source (English only).

import (
	"encoding/csv"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// cldrLocales maps our ISO-639-3 locale codes to their CLDR source locale.
var cldrLocales = []struct{ ours, cldr string }{
	{"ukr", "uk"}, {"eng", "en"}, {"spa", "es-419"}, {"por", "pt"},
}

func cldrURL(loc, kind string) string {
	return "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-localenames-full/main/" + loc + "/" + kind + ".json"
}

// cldrDisplayNames fetches one CLDR localeDisplayNames sub-map (territories|languages|scripts) for a locale.
func cldrDisplayNames(cldrLoc, kind string) (map[string]string, error) {
	b, err := fetchCached(cldrURL(cldrLoc, kind), "cldr-"+cldrLoc+"-"+kind+".json")
	if err != nil {
		return nil, err
	}
	var doc struct {
		Main map[string]struct {
			LocaleDisplayNames map[string]map[string]string `json:"localeDisplayNames"`
		} `json:"main"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		return nil, err
	}
	for _, m := range doc.Main {
		if names, ok := m.LocaleDisplayNames[kind]; ok {
			return names, nil
		}
	}
	return nil, fmt.Errorf("cldr %s/%s: no %s block", cldrLoc, kind, kind)
}

// translationRecord builds one {entityType, key, names} record from a per-locale name map (nil names drop).
func translationRecord(entityType, key string, names map[string]string) map[string]any {
	return map[string]any{"entityType": entityType, "key": key, "names": names}
}

// genTranslations assembles the whole translations preset from CLDR + curated sources.
func genTranslations(root string) error {
	var recs []map[string]any
	c, err := cldrCountryTranslations()
	if err != nil {
		return err
	}
	recs = append(recs, c...)
	sc, err := cldrScriptTranslations()
	if err != nil {
		return err
	}
	recs = append(recs, sc...)
	lg, err := cldrLanguageTranslations(root)
	if err != nil {
		return err
	}
	recs = append(recs, lg...)
	recs = append(recs, curatedColorTranslations()...)
	recs = append(recs, curatedReligionTranslations()...)
	rk, err := rankTranslations(root)
	if err != nil {
		return err
	}
	recs = append(recs, rk...)

	sort.SliceStable(recs, func(i, j int) bool {
		if recs[i]["entityType"] != recs[j]["entityType"] {
			return recs[i]["entityType"].(string) < recs[j]["entityType"].(string)
		}
		return recs[i]["key"].(string) < recs[j]["key"].(string)
	})
	return writePreset(root, manifest{
		preset:        "translations",
		objectType:    "translations",
		source:        "cldr+curated",
		sourceVersion: "2026.1",
		license:       "CC-BY-4.0+curated",
		dependsOn:     []string{"languages", "writing-systems", "countries", "religions", "colors", "ranks"},
		comment: "pinax preset — translations (i18n overlay). D-Pinax + D-i18n (M45), objectType translations.\n" +
			"GENERATED by deploy/pinax-presets/gen — do not hand-edit. (entityType,key,names{locale->text}) rows\n" +
			"for ukr/eng/spa/por: CLDR uk/en/es-419/pt for countries, writing systems and CLDR-known languages;\n" +
			"hand-curated for colors, religions and ranks. Resolved to the i18n store create-if-absent; dependsOn\n" +
			"the entity presets. Ethnicities have no multilingual source (English-only, no rows here).",
	}, recs)
}

// cldrCountryTranslations emits country name translations keyed by ISO alpha-2 (entity_type=country).
func cldrCountryTranslations() ([]map[string]any, error) {
	byLoc := map[string]map[string]string{}
	for _, l := range cldrLocales {
		names, err := cldrDisplayNames(l.cldr, "territories")
		if err != nil {
			return nil, err
		}
		byLoc[l.ours] = names
	}
	// The universe of codes = the alpha-2 (2 uppercase letters) territory keys.
	codes := map[string]bool{}
	for _, names := range byLoc {
		for code := range names {
			if len(code) == 2 && code == strings.ToUpper(code) {
				codes[code] = true
			}
		}
	}
	return emitPerLocale("country", codes, byLoc, nil), nil
}

// cldrScriptTranslations emits writing-system name translations keyed by ISO-15924 (entity_type=writing_system).
func cldrScriptTranslations() ([]map[string]any, error) {
	byLoc := map[string]map[string]string{}
	for _, l := range cldrLocales {
		names, err := cldrDisplayNames(l.cldr, "scripts")
		if err != nil {
			return nil, err
		}
		byLoc[l.ours] = names
	}
	codes := map[string]bool{}
	for _, names := range byLoc {
		for code := range names {
			if len(code) == 4 { // ISO-15924 is 4 letters (Latn, Cyrl, …)
				codes[code] = true
			}
		}
	}
	return emitPerLocale("writing_system", codes, byLoc, nil), nil
}

// cldrLanguageTranslations emits languoid name translations keyed by glottocode. CLDR names are keyed by
// BCP-47 subtag (mostly ISO 639-1); we map subtag→ISO-639-3 (iso-639-3.tab) →the language-level glottocode
// (from the Glottolog payload). Only CLDR-known languages with a resolvable glottocode get rows.
func cldrLanguageTranslations(root string) ([]map[string]any, error) {
	iso1to3, err := iso639Part1To3()
	if err != nil {
		return nil, err
	}
	iso3ToGlotto, err := iso3ToGlottocode(root)
	if err != nil {
		return nil, err
	}
	// subtag -> glottocode (subtag may be 2-letter ISO-639-1 or 3-letter ISO-639-3).
	subtagGlotto := func(subtag string) string {
		s := strings.ToLower(subtag)
		if len(s) == 2 {
			if i3, ok := iso1to3[s]; ok {
				return iso3ToGlotto[i3]
			}
			return ""
		}
		if len(s) == 3 {
			return iso3ToGlotto[s]
		}
		return ""
	}
	byLoc := map[string]map[string]string{}
	for _, l := range cldrLocales {
		names, err := cldrDisplayNames(l.cldr, "languages")
		if err != nil {
			return nil, err
		}
		byLoc[l.ours] = names
	}
	// Universe of subtags across locales that resolve to a glottocode; key the record by glottocode.
	keyed := map[string]string{} // glottocode -> subtag (first wins, deterministic via sorted subtags)
	subtags := map[string]bool{}
	for _, names := range byLoc {
		for st := range names {
			subtags[st] = true
		}
	}
	ordered := make([]string, 0, len(subtags))
	for st := range subtags {
		ordered = append(ordered, st)
	}
	sort.Strings(ordered)
	for _, st := range ordered {
		if gc := subtagGlotto(st); gc != "" {
			if _, seen := keyed[gc]; !seen {
				keyed[gc] = st
			}
		}
	}
	out := make([]map[string]any, 0, len(keyed))
	for gc, st := range keyed {
		names := map[string]string{}
		for _, l := range cldrLocales {
			if t := byLoc[l.ours][st]; t != "" {
				names[l.ours] = t
			}
		}
		if len(names) > 0 {
			out = append(out, translationRecord("languoid", gc, names))
		}
	}
	return out, nil
}

// emitPerLocale builds one record per key with a names map assembled across locales (skips empty).
func emitPerLocale(entityType string, keys map[string]bool, byLoc map[string]map[string]string, _ any) []map[string]any {
	out := make([]map[string]any, 0, len(keys))
	for key := range keys {
		names := map[string]string{}
		for _, l := range cldrLocales {
			if t := byLoc[l.ours][key]; t != "" {
				names[l.ours] = t
			}
		}
		if len(names) > 0 {
			out = append(out, translationRecord(entityType, key, names))
		}
	}
	return out
}

// iso639Part1To3 returns the ISO 639-1 (2-letter) → ISO 639-3 (3-letter) map from the datasets/
// language-codes table (columns: alpha3-b, alpha3-t, alpha2, English, French). The 639-2/T code equals
// the 639-3 code where it exists (e.g. de→deu); we prefer it, falling back to 639-2/B (e.g. uk→ukr).
func iso639Part1To3() (map[string]string, error) {
	b, err := fetchCached("https://raw.githubusercontent.com/datasets/language-codes/main/data/language-codes-full.csv", "language-codes-full.csv")
	if err != nil {
		return nil, err
	}
	r := csv.NewReader(strings.NewReader(string(b)))
	r.LazyQuotes = true
	r.FieldsPerRecord = -1
	rows, err := r.ReadAll()
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for i, row := range rows {
		if i == 0 || len(row) < 3 {
			continue // header / short
		}
		alpha3b := strings.ToLower(strings.TrimSpace(row[0]))
		alpha3t := strings.ToLower(strings.TrimSpace(row[1]))
		alpha2 := strings.ToLower(strings.TrimSpace(row[2]))
		if len(alpha2) != 2 {
			continue
		}
		if alpha3t != "" {
			out[alpha2] = alpha3t
		} else if alpha3b != "" {
			out[alpha2] = alpha3b
		}
	}
	return out, nil
}

// iso3ToGlottocode maps ISO-639-3 → the language-level glottocode from the Glottolog payload (a language
// row wins over a dialect/family sharing the ISO; first language row by code order otherwise).
func iso3ToGlottocode(root string) (map[string]string, error) {
	var raw []struct {
		Code, Level, ISO string
	}
	// decode with explicit tags (the payload uses lowercase keys code/level/iso639_3).
	b, err := os.ReadFile(filepath.Join(root, "deploy", "language-presets", "glottolog-5.3.json"))
	if err != nil {
		return nil, err
	}
	var recs []map[string]any
	if err := json.Unmarshal(b, &recs); err != nil {
		return nil, err
	}
	_ = raw
	sort.SliceStable(recs, func(i, j int) bool { return str(recs[i]["code"]) < str(recs[j]["code"]) })
	out := map[string]string{}
	for _, r := range recs {
		iso := strings.ToLower(str(r["iso639_3"]))
		if iso == "" {
			continue
		}
		if str(r["level"]) == "language" {
			if _, ok := out[iso]; !ok || str(r["level"]) == "language" {
				out[iso] = str(r["code"])
			}
		} else if _, ok := out[iso]; !ok {
			out[iso] = str(r["code"])
		}
	}
	return out, nil
}

// rankTranslations parses ranks.yaml and emits spa/por translations for categories, types and ranks whose
// default (English/Ukrainian) name is in the curated dictionaries. Keys are the "system/category[/type]/code"
// paths the pinax translations handler resolves. Uncurated names are left English-only (no row).
func rankTranslations(root string) ([]map[string]any, error) {
	b, err := os.ReadFile(filepath.Join(root, "internal", "pinax", "presets", "ranks.yaml"))
	if err != nil {
		return nil, err
	}
	var doc struct {
		Records []rankSystemY `yaml:"records"`
	}
	if err := yaml.Unmarshal(b, &doc); err != nil {
		return nil, err
	}
	var out []map[string]any
	add := func(entityType, key, name string) {
		if tr, ok := rankDict[strings.TrimSpace(name)]; ok {
			out = append(out, translationRecord(entityType, key, map[string]string{"spa": tr[0], "por": tr[1]}))
		}
	}
	for _, sys := range doc.Records {
		for _, cat := range sys.Categories {
			ck := sys.Code + "/" + cat.Code
			add("rank_category", ck, cat.Name)
			var walkTypes func(types []rankTypeY)
			walkTypes = func(types []rankTypeY) {
				for _, t := range types {
					add("rank_type", sys.Code+"/"+cat.Code+"/"+t.Code, t.Name)
					for _, rk := range t.Ranks {
						add("rank", sys.Code+"/"+cat.Code+"/"+rk.Code, rk.Name)
					}
					walkTypes(t.Children)
				}
			}
			walkTypes(cat.Types)
		}
	}
	return out, nil
}

type rankSystemY struct {
	Code       string     `yaml:"code"`
	Categories []rankCatY `yaml:"categories"`
}
type rankCatY struct {
	Code  string      `yaml:"code"`
	Name  string      `yaml:"name"`
	Types []rankTypeY `yaml:"types"`
}
type rankTypeY struct {
	Code     string      `yaml:"code"`
	Name     string      `yaml:"name"`
	Children []rankTypeY `yaml:"children"`
	Ranks    []rankRankY `yaml:"ranks"`
}
type rankRankY struct {
	Code string `yaml:"code"`
	Name string `yaml:"name"`
}
