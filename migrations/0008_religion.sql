-- religion_taxa_closure — derived transitive closure of the taxonomy tree (mirrors
-- education_unit_closure / language_languoid_closure). Composite key, no RID; reflexive (t,t,0) row.
-- Rebuilt in SQL on every taxon insert/reparent by the application; bulk-built from the seed below.
CREATE TABLE oikumenea.religion_taxa_closure (
  ancestor_id   uuid NOT NULL REFERENCES oikumenea.religion_taxa(id) ON DELETE CASCADE,
  descendant_id uuid NOT NULL REFERENCES oikumenea.religion_taxa(id) ON DELETE CASCADE,
  depth         integer NOT NULL,
  PRIMARY KEY (ancestor_id, descendant_id)
);
CREATE INDEX religion_taxa_closure_descendant_idx
  ON oikumenea.religion_taxa_closure (descendant_id);
COMMENT ON COLUMN oikumenea.religion_taxa_closure.ancestor_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa_closure.descendant_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa_closure.depth IS 'pii:none';

-- religion_taxon_classifications — theism tags on a taxon (M:N). Bare join, no RID. The resolution
-- (nearest-declared-wins down the closure) is computed at read time, never stored.
CREATE TABLE oikumenea.religion_taxon_classifications (
  taxon_id          uuid NOT NULL REFERENCES oikumenea.religion_taxa(id) ON DELETE CASCADE,
  classification_id uuid NOT NULL REFERENCES oikumenea.religion_classifications(id) ON DELETE RESTRICT,
  created_at        timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (taxon_id, classification_id)
);
COMMENT ON COLUMN oikumenea.religion_taxon_classifications.taxon_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxon_classifications.classification_id IS 'pii:none';

