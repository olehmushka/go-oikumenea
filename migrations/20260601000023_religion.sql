-- ===================================================================================================
-- Taxonomy: the recursive religion_taxa tree + its maintained closure (+ theism tags on taxa).
-- ===================================================================================================

-- religion_taxa — one node in the faith classification tree. `parent_id` is a strict-tree containment
-- self-FK (RESTRICT; NULL = a root religion) — NOT a reified Link. `rank_id` is the level marker;
-- `religion_id` is the denormalized root (derived via closure, below). `code` is unique among active.
CREATE TABLE oikumenea.religion_taxa (
  id             uuid PRIMARY KEY DEFAULT oikumenea.new_id(16,1,1),  -- religion / object / taxon
  parent_id      uuid REFERENCES oikumenea.religion_taxa(id) ON DELETE RESTRICT,  -- NULL = root religion
  rank_id        uuid NOT NULL REFERENCES oikumenea.religion_taxon_ranks(id) ON DELETE RESTRICT,
  religion_id    uuid REFERENCES oikumenea.religion_taxa(id) ON DELETE RESTRICT,  -- denormalized root (derived)
  code           text NOT NULL,
  name           text NOT NULL,                 -- default-locale display name; translatable via the i18n store
  description    text,
  wikidata_id    text,                          -- optional external anchor (e.g. Q5043)
  icon           text,
  sort_order     integer,
  source         text,                          -- importing/curating dataset id (provenance)
  source_version text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz,
  CONSTRAINT religion_taxa_rid_shape
    CHECK (oikumenea.rid_service(id)=16 AND oikumenea.rid_kind(id)=1 AND oikumenea.rid_type(id)=1),
  CONSTRAINT religion_taxa_not_self_parent CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE UNIQUE INDEX religion_taxa_code_active
  ON oikumenea.religion_taxa (code) WHERE deleted_at IS NULL;
CREATE INDEX religion_taxa_parent_idx ON oikumenea.religion_taxa (parent_id);
CREATE INDEX religion_taxa_rank_idx ON oikumenea.religion_taxa (rank_id) WHERE deleted_at IS NULL;
CREATE INDEX religion_taxa_religion_idx ON oikumenea.religion_taxa (religion_id) WHERE deleted_at IS NULL;
CREATE INDEX religion_taxa_wikidata_idx ON oikumenea.religion_taxa (wikidata_id) WHERE deleted_at IS NULL;
CREATE TRIGGER religion_taxa_set_updated_at
  BEFORE UPDATE ON oikumenea.religion_taxa
  FOR EACH ROW EXECUTE FUNCTION oikumenea.set_updated_at();
COMMENT ON COLUMN oikumenea.religion_taxa.id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa.parent_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa.rank_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa.religion_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa.code IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa.name IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa.wikidata_id IS 'pii:none';

-- religion_taxa_closure — derived transitive closure of the taxonomy tree (mirrors
-- education_unit_closure / language_languoid_closure). Composite key, no RID; reflexive (t,t,0) row.
-- Rebuilt in SQL on every taxon insert/reparent by the application; bulk-built from the seed below.
CREATE TABLE oikumenea.religion_taxa_closure (
  ancestor_id   uuid NOT NULL REFERENCES oikumenea.religion_taxa(id) ON DELETE CASCADE,
  descendant_id uuid NOT NULL REFERENCES oikumenea.religion_taxa(id) ON DELETE CASCADE,
  depth         integer NOT NULL,
  PRIMARY KEY (ancestor_id, descendant_id)
);
CREATE INDEX religion_taxa_closure_descendant_idx
  ON oikumenea.religion_taxa_closure (descendant_id);
COMMENT ON COLUMN oikumenea.religion_taxa_closure.ancestor_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa_closure.descendant_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxa_closure.depth IS 'pii:none';

-- religion_taxon_classifications — theism tags on a taxon (M:N). Bare join, no RID. The resolution
-- (nearest-declared-wins down the closure) is computed at read time, never stored.
CREATE TABLE oikumenea.religion_taxon_classifications (
  taxon_id          uuid NOT NULL REFERENCES oikumenea.religion_taxa(id) ON DELETE CASCADE,
  classification_id uuid NOT NULL REFERENCES oikumenea.religion_classifications(id) ON DELETE RESTRICT,
  created_at        timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (taxon_id, classification_id)
);
COMMENT ON COLUMN oikumenea.religion_taxon_classifications.taxon_id IS 'pii:none';
COMMENT ON COLUMN oikumenea.religion_taxon_classifications.classification_id IS 'pii:none';

