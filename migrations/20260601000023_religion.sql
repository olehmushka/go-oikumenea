-- religion_taxon_ranks — the ordered STRUCTURAL level scaffold (religion → branch → tradition →
-- sub_tradition → denomination). Structural, not faith vocabulary; a faith need not use every level
-- (the closure carries true depth). Extensible.
CREATE TABLE oikumenea.religion_taxon_ranks (
  id         uuid PRIMARY KEY DEFAULT oikumenea.new_id(16,1,2),  -- religion / object / taxon_rank
  code       text NOT NULL,
  name       text NOT NULL,                  -- default-locale display name; translatable via the i18n store
  ordinal    integer NOT NULL,               -- relative depth/rank of the level (religion=0 … denomination=4)
  status     text NOT NULL DEFAULT 'active' CHECK (status IN ('active','retired')),
  sort_order integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT religion_taxon_ranks_rid_shape
    CHECK (oikumenea.rid_service(id)=16 AND oikumenea.rid_kind(id)=1 AND oikumenea.rid_type(id)=2)
);
CREATE UNIQUE INDEX religion_taxon_ranks_code_active
