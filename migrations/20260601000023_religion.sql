-- 0023 religion (M22 — Religion core: multi-faith taxonomy & organization).
--
-- The religion domain (docs/modules/religion.md / D-Religion, refined M22 design 2026-06-19). This is
-- the M22 SLICE ONLY: the faith taxonomy + the organization attributes. Clergy (M23), lay affiliation
-- (M24) and discovery/sites (M25) are designed-but-deferred and ship in later migrations.
--
-- Binding design rule (D-Religion): NO faith's vocabulary is hard-coded. Every faith term — religion,
-- branch, tradition, denomination, theism type, org kind, policy kind — is a CATALOG ROW (D-Code /
-- D-i18n), never a CHECK enum and never an `if faith == …` branch. The only CHECK enums here are fixed
-- lifecycle statuses.
--
-- Taxonomy shape (refined): a SINGLE recursive `religion_taxa` tree (parent_id self-FK) + a maintained
-- `religion_taxa_closure` — reusing the proven language_languoids-forest / education_unit_closure
-- pattern, NOT three fixed catalog tables. Each taxon carries a catalog-driven level marker
-- (`rank_id` → religion_taxon_ranks: religion→branch→tradition→sub_tradition→denomination) so the main
-- branches stay findable, an optional `wikidata_id` anchor, and a denormalized root `religion_id`
-- (derived via the closure here, like language_languoids.family_code).
--
-- Organization: a religious body is a tenant_units row (reused, not a new hierarchy) placed in the
-- three seeded religion graphs (canonical authority-bearing; tradition + affiliation directory-only).
-- A unit's faith attributes are religion_org_profiles (1:1, keyed by the unit RID) + the M:N
-- religion_org_classifications (many tradition tags, one primary). Religion-type (theism) classification
-- resolves nearest-declared-wins down the closure, and a unit may override via religion_unit_classifications.
--
-- new_id() reads no GUC (D-ResourceIdentifiers), so the curated taxonomy seed (generated by the
-- reproducible deploy/religion-presets/gen-presets.py, anchored to Wikidata QIDs) is embedded directly.
--
-- RLS: the four UNIT-SCOPED tables (org_profiles / org_classifications / unit_classifications /
-- org_policies) carry the app.readable_units / app.writable_units backstop (D-RLSDefenseInDepth),
-- mirroring membership_positions. The instance-level catalogs + the taxonomy tree/closure carry NO RLS
-- (reference data, not scoped to tenant_units — like education and tenant_graphs/closure).
--
-- Expand-only (L-UpgradeSafe / D-Migrations); depends on 0000 (new_id), 0003 tenant (tenant_units /
-- tenant_graphs), 0005 person (person_persons) and 0011 (the RLS app role).

